<script lang="ts">
  // Settings: theme, language, updates; and the version.
  import { onMount, untrack } from "svelte";
  import { getVersion } from "@tauri-apps/api/app";
  import { invoke } from "@tauri-apps/api/core";
  import { languages, t, type LangSetting } from "./i18n.svelte";
  import type { Key } from "./i18n.svelte";
  import type { Theme } from "./look";
  import Icon from "./Icon.svelte";
  import { LOGO_SVG } from "./logo";

  const THEMES: [Theme, string, Key][] = [
    ["system", "monitor", "set.system"],
    ["light", "sun", "set.light"],
    ["dark", "moon", "set.dark"],
  ];

  interface Props {
    theme: Theme;
    language: LangSetting;
    checkUpdates: boolean;
    author: string;
    /** Used when `author` is empty. */
    defaultAuthor: string;
    onauthor: (a: string) => void;
    onchange: (s: { theme: Theme; language: LangSetting; checkUpdates: boolean }) => void;
    /** Looks for an update now; resolves to the new version, or null if up to date. */
    oncheck: () => Promise<string | null>;
    onclose: () => void;
  }
  let { theme, language, checkUpdates, author, defaultAuthor, onauthor, onchange, oncheck, onclose }: Props =
    $props();

  // Edited here; the app is told of every change.
  let th: Theme = $state(untrack(() => theme));
  let lg: LangSetting = $state(untrack(() => language));
  let up = $state(untrack(() => checkUpdates));
  let version = $state("");
  let checking = $state(false);
  let checkResult = $state("");
  let first: HTMLInputElement | null = $state(null);
  let licenses: string | null = $state(null);

  async function showLicenses() {
    licenses =
      licenses === null ? await invoke<string>("third_party_licenses").catch((e) => String(e)) : null;
  }

  function changed() {
    onchange({ theme: th, language: lg, checkUpdates: up });
  }

  async function checkNow() {
    checking = true;
    checkResult = "";
    const found = await oncheck();
    checking = false;
    // When there is one, the update banner shows it.
    checkResult = found ? "" : t("set.upToDate", { version });
  }

  onMount(() => {
    first?.focus();
    void getVersion()
      .then((v) => (version = v))
      .catch(() => {});
  });
</script>

<div
  class="overlay"
  role="presentation"
  onkeydown={(e) => {
    if (e.key === "Escape") {
      e.stopPropagation();
      onclose();
    }
  }}
>
  <div class="dialog" role="dialog" aria-modal="true" aria-labelledby="settings-title">
    <header class="head">
      <!-- eslint-disable-next-line svelte/no-at-html-tags -- generated by scripts/gen-brand.py -->
      <span class="logo" aria-hidden="true">{@html LOGO_SVG}</span>
      <h1 id="settings-title">{t("set.title")}</h1>
      <button
        type="button"
        class="close"
        onclick={onclose}
        aria-label={t("common.close")}
        title={t("common.close")}
      >
        <Icon name="close" size={16} />
      </button>
    </header>

    <div class="body">
      <section class="card">
        <fieldset>
          <legend><Icon name="sun" size={18} />{t("set.theme")}</legend>
          <div class="tiles">
            {#each THEMES as [id, icon, key] (id)}
              <label class="tile" class:on={th === id}>
                {#if id === "system"}
                  <input type="radio" bind:group={th} value={id} bind:this={first} onchange={changed} />
                {:else}
                  <input type="radio" bind:group={th} value={id} onchange={changed} />
                {/if}
                <span class="tile-art"><Icon name={icon} size={26} /></span>
                {t(key)}
              </label>
            {/each}
          </div>
        </fieldset>
      </section>

      <section class="card">
        <fieldset>
          <legend><Icon name="globe" size={18} />{t("set.language")}</legend>
          <div class="seg">
            <label class:on={lg === "system"}>
              <input type="radio" bind:group={lg} value="system" onchange={changed} />
              {t("set.system")}
            </label>
            {#each languages as l (l.id)}
              <label lang={l.id} class:on={lg === l.id}>
                <input type="radio" bind:group={lg} value={l.id} onchange={changed} />
                {l.name}
              </label>
            {/each}
          </div>
        </fieldset>
      </section>

      <section class="card">
        <label class="row field">
          <span class="row-label"><Icon name="person" size={18} />{t("set.author")}</span>
          <input
            type="text"
            dir="auto"
            value={author}
            placeholder={defaultAuthor}
            onchange={(e) => onauthor(e.currentTarget.value.trim())}
          />
        </label>
      </section>

      <section class="card">
        <div class="row">
          <span class="row-label"><Icon name="refresh" size={18} />{t("set.updatesTitle")}</span>
          <button type="button" onclick={checkNow} disabled={checking}>
            {checking ? t("set.checking") : t("set.checkNow")}
          </button>
        </div>
        <label class="row switch-row">
          <span class="muted">{t("set.updates")}</span>
          <input class="switch" type="checkbox" role="switch" bind:checked={up} onchange={changed} />
        </label>
        {#if checkResult}<p class="result" aria-live="polite">{checkResult}</p>{/if}
      </section>

      <section class="card about">
        <!-- eslint-disable-next-line svelte/no-at-html-tags -- generated by scripts/gen-brand.py -->
        <span class="about-mark" aria-hidden="true">{@html LOGO_SVG}</span>
        <div>
          <strong>{t("set.aboutTitle")}</strong>
          {#if version}<span class="muted"> · {t("set.version", { version })}</span>{/if}
          <p class="muted">
            {t("set.about")}
            <button type="button" class="link" onclick={showLicenses}>{t("set.licenses")}</button>
          </p>
        </div>
      </section>
      {#if licenses !== null}
        <pre class="licenses" dir="ltr">{licenses}</pre>
      {/if}
    </div>

    <div class="actions">
      <button type="button" class="primary" onclick={onclose}>{t("common.close")}</button>
    </div>
  </div>
</div>

