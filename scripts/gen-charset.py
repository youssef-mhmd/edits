"""Generate crates/edits-ocr/src/charset_data.rs from arabic-ocr's charset.py.

    uv run --project ../arabic-ocr python -I scripts/gen-charset.py ../arabic-ocr

arabic-ocr's charset.py is the single source of truth for what the recognizer
can output (ids are positions in its symbol list). The generated file holds,
for every symbol, the Unicode properties the pipeline needs (bidi class, letter
or number, isalpha), so edits-ocr needs no Unicode tables of its own. Every
character is written as an escape, so the file is plain ASCII.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path


def esc(ch: str) -> str:
    return f"'\\u{{{ord(ch):04X}}}'"


def main() -> None:
    root = Path(sys.argv[1])
    sys.path.insert(0, str(root / "src"))
    from arabic_ocr import charset
    from arabic_ocr.correct import GROUPS

    bidi_names = sorted({unicodedata.bidirectional(c) or "ON" for c in charset.SYMBOLS})
    lines = [
        "// Generated by scripts/gen-charset.py from arabic-ocr's charset.py. Do not edit.",
        "",
        f'pub const FINGERPRINT: &str = "{charset.fingerprint()}";',
        f"pub const NUM_CLASSES: usize = {charset.NUM_CLASSES};",
        "",
        "/// Bidi class of a symbol (Unicode UAX #9).",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub enum Bidi {",
        *[f"    {b}," for b in bidi_names],
        "}",
        "",
        "/// A symbol: its character, bidi class, Unicode general category (first",
        "/// letter: 'L' letter, 'N' number, 'M' mark, 'P' punctuation, 'S' symbol,",
        "/// 'Z' separator) and Python's str.isalpha().",
        "pub struct Symbol {",
        "    pub ch: char,",
        "    pub bidi: Bidi,",
        "    pub category: u8,",
        "    pub alpha: bool,",
        "}",
        "",
        "/// Symbol id i + 1 (id 0 is the CTC blank).",
        "pub const SYMBOLS: &[Symbol] = &[",
    ]
    for c in charset.SYMBOLS:
        bidi = unicodedata.bidirectional(c) or "ON"
        cat = unicodedata.category(c)[0]
        lines.append(
            f"    Symbol {{ ch: {esc(c)}, bidi: Bidi::{bidi}, category: b'{cat}', "
            f"alpha: {str(c.isalpha()).lower()} }},"
        )
    lines.append("];")

    def table(name: str, chars, doc: str) -> None:
        lines.extend(["", f"/// {doc}", f"pub const {name}: &[char] = &["])
        lines.extend(f"    {esc(c)}," for c in chars)
        lines.append("];")

    table("DIACRITICS", charset.DIACRITICS, "Tashkeel, as in charset.DIACRITICS.")
    table("ARABIC_INDIC_DIGITS", charset.ARABIC_INDIC_DIGITS, "U+0660..U+0669.")
    table("EASTERN_DIGITS", charset.EASTERN_ARABIC_INDIC_DIGITS, "U+06F0..U+06F9.")
    lines.extend(["", f"pub const TATWEEL: char = {esc(charset.TATWEEL)};"])
    lines.extend(["", "/// Letters told apart only by dots (correct.GROUPS).", "pub const TWIN_GROUPS: &[&[char]] = &["])
    for g in GROUPS:
        lines.append("    &[" + ", ".join(esc(c) for c in g) + "],")
    lines.append("];")

    out = Path(__file__).resolve().parents[1] / "crates" / "edits-ocr" / "src" / "charset_data.rs"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="ascii", newline="")
    print(f"{len(charset.SYMBOLS)} symbols, fingerprint {charset.fingerprint()} -> {out}")


if __name__ == "__main__":
    main()
